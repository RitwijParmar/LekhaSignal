-- LekhaSignal Snowflake deployment blueprint. Run with ACCOUNTADMIN only for initial setup.
CREATE OR REPLACE ROLE LEKHASIGNAL_PLATFORM_ADMIN;
CREATE OR REPLACE ROLE LEKHASIGNAL_TRANSFORMER;
CREATE OR REPLACE ROLE LEKHASIGNAL_ANALYST;
CREATE OR REPLACE WAREHOUSE LEKHASIGNAL_INGEST_WH WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE OR REPLACE WAREHOUSE LEKHASIGNAL_TRANSFORM_WH WITH WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE OR REPLACE RESOURCE MONITOR LEKHASIGNAL_DAILY_CREDITS WITH CREDIT_QUOTA = 50 FREQUENCY = DAILY START_TIMESTAMP = IMMEDIATELY TRIGGERS ON 75 PERCENT DO NOTIFY ON 90 PERCENT DO SUSPEND;
ALTER WAREHOUSE LEKHASIGNAL_TRANSFORM_WH SET RESOURCE_MONITOR = LEKHASIGNAL_DAILY_CREDITS;
CREATE OR REPLACE DATABASE LEKHASIGNAL;
CREATE OR REPLACE SCHEMA LEKHASIGNAL.RAW;
CREATE OR REPLACE SCHEMA LEKHASIGNAL.CORE;
CREATE OR REPLACE SCHEMA LEKHASIGNAL.MART;
CREATE OR REPLACE SCHEMA LEKHASIGNAL.CONTROL;

CREATE OR REPLACE TABLE LEKHASIGNAL.RAW.PAYMENT_EVENTS (
  event_id STRING, payment_id STRING, invoice_id STRING, customer_id STRING,
  amount NUMBER(18,2), currency STRING, event_ts TIMESTAMP_TZ, source_lsn NUMBER,
  payload VARIANT, ingest_ts TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE OR REPLACE TABLE LEKHASIGNAL.RAW.INVOICE_EVENTS (
  event_id STRING, invoice_id STRING, customer_id STRING, invoice_status STRING,
  invoice_total NUMBER(18,2), issued_at TIMESTAMP_TZ, source_lsn NUMBER,
  payload VARIANT, ingest_ts TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

