CREATE OR REPLACE MASKING POLICY LEKHASIGNAL.CONTROL.EMAIL_MASK AS (value STRING) RETURNS STRING ->
  CASE WHEN CURRENT_ROLE() IN ('LEKHASIGNAL_PLATFORM_ADMIN','LEKHASIGNAL_ANALYST') THEN value ELSE '***masked***' END;

GRANT USAGE ON DATABASE LEKHASIGNAL TO ROLE LEKHASIGNAL_TRANSFORMER, LEKHASIGNAL_ANALYST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE LEKHASIGNAL TO ROLE LEKHASIGNAL_TRANSFORMER, LEKHASIGNAL_ANALYST;
GRANT SELECT ON FUTURE TABLES IN DATABASE LEKHASIGNAL TO ROLE LEKHASIGNAL_ANALYST;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN DATABASE LEKHASIGNAL TO ROLE LEKHASIGNAL_TRANSFORMER;
